#!/bin/bash

# 定义你指定的测试节点
declare -A nodes
nodes=(
    ["电信_北京"]="219.141.147.210"
    ["电信_上海"]="202.96.209.133"
    ["电信_广州"]="202.96.128.86"
    ["联通_北京"]="202.106.50.1"
    ["联通_上海"]="210.22.97.1"
    ["联通_深圳"]="120.80.169.1"
    ["移动_北京"]="221.183.46.218"
    ["移动_上海"]="211.136.112.200"
    ["移动_广州"]="120.196.165.24"
    ["教育_成都"]="202.112.14.151"
)

# 节点排序序列（确保输出按运营商分组）
order=("电信_北京" "电信_上海" "电信_广州" "联通_北京" "联通_上海" "联通_深圳" "移动_北京" "移动_上海" "移动_广州" "教育_成都")

echo -e "\e[1;36m=== VPS 线路质量专项对比测试 (100个包) ===\e[0m"
echo "当前时间: $(date)"
echo "测试机器: $(hostname)"
echo "--------------------------------------------------------"
printf "%-15s | %-16s | %-10s | %-10s\n" "节点名称" "目标 IP" "平均延迟" "丢包率"
echo "--------------------------------------------------------"

for name in "${order[@]}"; do
    target=${nodes[$name]}
    
    # 执行快速 ping（0.2秒间隔需要 sudo）
    # 发送 100 个包
    result=$(ping -c 100 -i 0.2 -q $target 2>/dev/null)
    
    if [ $? -ne 0 ]; then
        # 如果 ping 失败（可能节点宕机或禁 ping）
        printf "%-12s | %-15s | \e[31m%-8s\e[0m | \e[31m%-10s\e[0m\n" "$name" "$target" "FAILED" "100%"
        continue
    fi

    # 提取平均延迟 (rtt min/avg/max/mdev)
    avg=$(echo "$result" | awk -F'/' 'END{print $5}')
    # 提取丢包率
    loss=$(echo "$result" | grep -oP '\d+(?=% packet loss)')
    
    # 丢包率着色逻辑
    if [ "$loss" -eq 0 ]; then
        loss_display="\e[32m${loss}%\e[0m"   # 0% 绿色
    elif [ "$loss" -le 3 ]; then
        loss_display="\e[33m${loss}%\e[0m"   # 1-3% 黄色（GIA 线路不该丢包）
    else
        loss_display="\e[31m${loss}%\e[0m"   # >3% 红色（警告）
    fi

    printf "%-12s | %-15s | %-8s ms | %-10b\n" "$name" "$target" "$avg" "$loss_display"
done

echo "--------------------------------------------------------"
echo -e "\e[1;33m测试说明：\e[0m"
echo "1. 东京机(TYO)应重点关注广州节点延迟；洛杉矶机(LAX)关注丢包率稳定性。"
echo "2. 建议在 21:00 - 23:00 (晚高峰) 运行此脚本获取最具参考价值的数据。"
